const MAELSTROM_LANGUAGES = [
  { code: "en", flag: "🇬🇧", label: "English" },
  { code: "fr", flag: "🇫🇷", label: "Français" },
  { code: "no", flag: "🇳🇴", label: "Norsk" },
];

function getSavedLanguage() {
  try {
    return localStorage.getItem(MAELSTROM_I18N_STORAGE);
  } catch {
    return null;
  }
}

function getInitialLanguage() {
  const saved = getSavedLanguage();
  if (saved && MAELSTROM_TRANSLATIONS[saved]) {
    return saved;
  }

  const browserLanguage = navigator.language?.slice(0, 2).toLowerCase();
  return MAELSTROM_TRANSLATIONS[browserLanguage] ? browserLanguage : "en";
}

function translate(key, language = window.MaelstromI18n?.language || getInitialLanguage()) {
  return MAELSTROM_TRANSLATIONS[language]?.[key] || MAELSTROM_TRANSLATIONS.en[key] || key;
}

function applyLanguage(language) {
  const chosen = MAELSTROM_TRANSLATIONS[language] ? language : "en";
  const activeLanguage = MAELSTROM_LANGUAGES.find((item) => item.code === chosen) || MAELSTROM_LANGUAGES[0];
  window.MaelstromI18n.language = chosen;
  document.documentElement.lang = chosen === "no" ? "nb" : chosen;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n, chosen);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria, chosen));
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(element.dataset.i18nPlaceholder, chosen));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", translate(element.dataset.i18nAlt, chosen));
  });

  document.querySelectorAll("[data-language-option]").forEach((button) => {
    const active = button.dataset.languageOption === chosen;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.querySelector(".language-switcher")?.setAttribute("aria-label", translate("languageLabel", chosen));

  const trigger = document.querySelector("[data-language-toggle]");
  if (trigger) {
    trigger.setAttribute("aria-label", translate("languageLabel", chosen));
    trigger.querySelector("[data-current-language-flag]").textContent = activeLanguage.flag;
  }

  try {
    localStorage.setItem(MAELSTROM_I18N_STORAGE, chosen);
  } catch {
    // Ignore storage failures; the current page still changes language.
  }

  window.dispatchEvent(new CustomEvent("maelstrom:languagechange", { detail: { language: chosen } }));
}

function createLanguageSelector() {
  const header = document.querySelector(".site-header");
  if (!header || document.querySelector(".language-switcher")) {
    return;
  }

  const switcher = document.createElement("div");
  switcher.className = "language-switcher";
  switcher.setAttribute("aria-label", translate("languageLabel"));

  switcher.innerHTML = `
    <button class="language-toggle" type="button" data-language-toggle aria-expanded="false" aria-label="${translate("languageLabel")}">
      <span data-current-language-flag aria-hidden="true">${MAELSTROM_LANGUAGES[0].flag}</span>
      <span class="language-toggle-flags" aria-hidden="true">${MAELSTROM_LANGUAGES.map((language) => language.flag).join("")}</span>
    </button>
    <div class="language-options" role="group">
      ${MAELSTROM_LANGUAGES.map((language) => `
        <button type="button" data-language-option="${language.code}" aria-label="${language.label}" aria-pressed="false">
          <span aria-hidden="true">${language.flag}</span>
          <span>${language.code.toUpperCase()}</span>
        </button>
      `).join("")}
    </div>
  `;

  switcher.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-language-toggle]");
    if (trigger) {
      const open = switcher.classList.toggle("is-open");
      trigger.setAttribute("aria-expanded", String(open));
      return;
    }

    const button = event.target.closest("[data-language-option]");
    if (button) {
      applyLanguage(button.dataset.languageOption);
      switcher.classList.remove("is-open");
      switcher.querySelector("[data-language-toggle]")?.setAttribute("aria-expanded", "false");
    }
  });

  document.addEventListener("click", (event) => {
    if (!switcher.contains(event.target)) {
      switcher.classList.remove("is-open");
      switcher.querySelector("[data-language-toggle]")?.setAttribute("aria-expanded", "false");
    }
  });

  header.appendChild(switcher);
}

window.MaelstromI18n = {
  language: getInitialLanguage(),
  t: translate,
  setLanguage: applyLanguage,
};

document.addEventListener("DOMContentLoaded", () => {
  createLanguageSelector();
  applyLanguage(window.MaelstromI18n.language);
});
